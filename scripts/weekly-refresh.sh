#!/usr/bin/env bash
# Weekly forecast refresh for machines without GitHub Actions.
#
# Rebuilds the forecast snapshot from upstream sources, commits it to main,
# and republishes the gh-pages branch. Point a local cron at this script:
#
#   17 3 * * 1 cd /home/terriaki/dev/bun/shittim-chest && bash scripts/weekly-refresh.sh >> .refresh.log 2>&1
#
# Usage: bash scripts/weekly-refresh.sh
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

git pull --ff-only origin main || true
bun install --frozen-lockfile
bun run export

git add public/data public/img
if git diff --quiet --cached; then
  echo "Forecast snapshot is already up to date."
else
  git commit -m "chore(data): weekly forecast refresh

Regenerated by scripts/weekly-refresh.sh (scripts/export.ts): fresh wiki +
SchaleDB snapshot, rebuilt predictions, mirrored artwork. See
public/data/status.json for the export time."
  git push origin main
fi

bash scripts/deploy-branch.sh
